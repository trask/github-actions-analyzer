"""Write the raw per-job data behind the queue-wait evidence, plus the aggregates
derived from it, so the published table can be checked or regenerated by others."""

import csv
import subprocess
import sys
import zipfile
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from github_actions_analyzer import JobRecord, _percentile  # noqa: E402

from incidents import (  # noqa: E402
    END,
    MERGE_GAP,
    MIN_JOBS,
    REPOS,
    STALL_P90,
    START,
    _minutes,
    _pct_record,
    find_episodes,
    in_window,
    load_bins,
)

OUT = Path("build/export")
ZIP = Path("build/queue-wait-raw-data.zip")


def _stats(records: list[JobRecord]) -> dict[str, float]:
    minutes = sorted(_minutes(record.queue_duration) for record in records)
    return {
        "jobs": len(minutes),
        "p50_min": round(_percentile(minutes, 50), 2),
        "p90_min": round(_percentile(minutes, 90), 2),
        "p99_min": round(_percentile(minutes, 99), 2),
        "max_min": round(minutes[-1], 2),
        "pct_over_10min": round(100 * sum(1 for m in minutes if m > 10) / len(minutes), 1),
    }


def _instant(moment: datetime) -> str:
    return moment.strftime("%Y-%m-%dT%H:%M:%SZ")


def _write_episodes(path: Path, bins, episodes) -> int:
    rows = 0
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(
            [
                "episode_start_utc", "episode_end_utc", "episode_minutes", "repo", "stalled",
                "jobs", "p50_min", "p90_min", "p99_min", "max_min", "pct_over_10min", "p90_job_url",
            ]
        )
        for start, end in episodes:
            for repo in REPOS:
                records = in_window(bins, repo, start, end)
                if not records:
                    continue
                stats = _stats(records)
                writer.writerow(
                    [
                        _instant(start), _instant(end), int(_minutes(end - start)), repo,
                        stats["p90_min"] > STALL_P90, stats["jobs"], stats["p50_min"],
                        stats["p90_min"], stats["p99_min"], stats["max_min"],
                        stats["pct_over_10min"], _pct_record(records, 90).html_url,
                    ]
                )
                rows += 1
    return rows


def _write_episode_jobs(path: Path, bins, episodes) -> int:
    rows = 0
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(
            [
                "episode_start_utc", "repo", "workflow", "job_name", "run_id", "job_id",
                "labels", "event", "from_fork", "runner_name", "created_at", "started_at",
                "wait_minutes", "html_url",
            ]
        )
        for start, end in episodes:
            for repo in REPOS:
                for record in sorted(in_window(bins, repo, start, end), key=lambda r: r.created_at):
                    writer.writerow(
                        [
                            _instant(start), record.repo, record.workflow, record.name,
                            record.run_id, record.job_id, record.labels, record.event,
                            record.from_fork, record.runner_name, _instant(record.created_at),
                            _instant(record.created_at + record.queue_duration),
                            round(_minutes(record.queue_duration), 2), record.html_url,
                        ]
                    )
                    rows += 1
    return rows


def _write_hourly(path: Path, bins, episodes) -> tuple[int, tuple[int, int]]:
    stalled_hours = {
        (start.replace(minute=0), repo)
        for start, end in episodes
        for repo in REPOS
        for records in [in_window(bins, repo, start, end)]
        if records and _stats(records)["p90_min"] > STALL_P90
    }
    rows = 0
    calm = busy = 0
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["hour_utc", "repo", "jobs", "p50_min", "p90_min", "p99_min", "max_min", "pct_over_10min"])
        for repo in REPOS:
            per_hour: dict[datetime, list[JobRecord]] = {}
            for binned in bins[repo].values():
                for record in binned:
                    per_hour.setdefault(record.created_at.replace(minute=0, second=0, microsecond=0), []).append(record)
            for hour in sorted(per_hour):
                stats = _stats(per_hour[hour])
                writer.writerow(
                    [
                        _instant(hour), repo, stats["jobs"], stats["p50_min"], stats["p90_min"],
                        stats["p99_min"], stats["max_min"], stats["pct_over_10min"],
                    ]
                )
                rows += 1
                if stats["jobs"] >= 50 and (hour, repo) not in stalled_hours:
                    busy += 1
                    calm += stats["p90_min"] <= STALL_P90
    return rows, (calm, busy)


def _readme(bins, episodes, counts: dict[str, int], baseline: tuple[int, int], commit: str) -> str:
    thin = [
        repo
        for repo in REPOS
        if sum(1 for start, end in episodes if in_window(bins, repo, start, end)) * 3 < len(episodes)
    ]
    calm, busy = baseline
    return f"""# GitHub Actions queue-wait raw data — open-telemetry

Backing data for https://github.com/open-telemetry/community/issues/3622.

Window: {_instant(START)} to {_instant(END)} ({(END - START).days} days), all times UTC.
Repositories: {", ".join(REPOS)}.

Generated by `build/export.py` in https://github.com/trask/github-actions-analyzer at commit {commit},
reading the GitHub Actions Workflow Runs and Workflow Jobs REST APIs. Every row is public data;
any `job_id` can be re-checked with `gh api repos/open-telemetry/<repo>/actions/jobs/<job_id>`.

## Files

- `episode-jobs.csv` ({counts["episode_jobs"]} rows) — one row per job inside the {len(episodes)} episodes. This is the raw data.
- `episodes.csv` ({counts["episodes"]} rows) — per episode per repository aggregates. Directly backs the published table.
- `hourly.csv` ({counts["hourly"]} rows) — per repository per hour across the whole window, including the unaffected hours.
  These are not cherry-picked worst moments: outside the stalled hours, {calm} of the {busy} busy hours
  (at least 50 hosted jobs) had a p90 wait of 10 minutes or less.

## Definitions

- Queue wait = `started_at - created_at` from the Workflow Jobs API, per job.
- Episode = 10-minute bucket with at least {MIN_JOBS} hosted jobs and p90 wait above {STALL_P90:.0f} minutes,
  merged with any other such bucket within {int(_minutes(MERGE_GAP))} minutes.
- Percentiles use the nearest-rank method on the sorted waits.

## Filters applied

- GitHub-hosted runner labels only (`ubuntu-*`, `windows-*`, `macos-*`). Donated self-hosted pools are excluded
  throughout; they queue for hours and would swamp the hosted numbers.
- First run attempt only, so retries are not double counted.
- Jobs that never got a runner are excluded. GitHub reports `started_at == created_at` for those, which hides
  the real wait; requiring a non-empty `runner_name` removes them. The `runner_name` column is included so this
  is checkable.
- Waits outside 0 to 6 hours are dropped as implausible.

## Known gaps

- 20 runs (<0.5%) are missing entirely: their jobs endpoint returns HTTP 502 permanently. The same runs also fail
  to render their own web summary page, so this is server side, not a client bug.
- `opentelemetry-go` was chosen as a control after observing it was unaffected. It shows hosted capacity existed
  in those same minutes; it is not a claim that it is immune.
- {", ".join(thin) or "No repository"} had hosted jobs in fewer than a third of the {len(episodes)} episodes,
  so a low stall count there is absence of data rather than evidence of health.
"""


def main() -> None:
    bins = load_bins()
    episodes = find_episodes(bins)
    OUT.mkdir(parents=True, exist_ok=True)

    hourly_rows, baseline = _write_hourly(OUT / "hourly.csv", bins, episodes)
    counts = {
        "episodes": _write_episodes(OUT / "episodes.csv", bins, episodes),
        "episode_jobs": _write_episode_jobs(OUT / "episode-jobs.csv", bins, episodes),
        "hourly": hourly_rows,
    }

    commit = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    (OUT / "README.md").write_text(_readme(bins, episodes, counts, baseline, commit), encoding="utf-8")

    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as archive:
        for name in ("README.md", "episodes.csv", "episode-jobs.csv", "hourly.csv"):
            archive.write(OUT / name, name)

    print(f"{len(episodes)} episodes")
    for name, count in counts.items():
        print(f"  {name:14} {count:>7} rows")
    print(f"{ZIP} {ZIP.stat().st_size / 1_000_000:.1f} MB")


if __name__ == "__main__":
    main()
